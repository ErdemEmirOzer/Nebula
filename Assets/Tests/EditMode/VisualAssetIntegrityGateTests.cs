    /// <summary>
    /// The acceptance criteria a photograph cannot settle.
    /// <para>
    /// A difference image proves the picture did not change. It cannot prove
    /// <i>why</i> it did not, and several of the defects the brief demands zero of
    /// are invisible in a single frame: a normal map with its green channel
    /// flipped looks wrong only under a light from one particular side, an sRGB
    /// flag on a roughness map reads as a slightly different surface rather than
    /// as an error, and a texture that decoded to black would only show on a
    /// model nobody thought to render. Each of those is settled here against the
    /// asset and the manifest instead.
    /// </para>
    /// <para>
    /// The strongest gate in this file is
    /// <see cref="EveryGeneratedTextureIsAByteForByteCopyOfTheImageItReplaced"/>.
    /// The optimizer's contract is that an extracted texture is a <i>verbatim</i>
    /// copy of one blob embedded in a GLB — not a re-encode, not a resample, not a
    /// channel swizzle. If the bytes match, then no pixel changed, and "black
    /// texture", "inverted normal", "wrong colour" and every other pixel-level
    /// defect are all excluded at once by one comparison rather than by a
    /// heuristic per defect.
    /// </para>
    /// </summary>
    public class VisualAssetIntegrityGateTests
    {
        private const string PrefabRoot = "Assets/Resources/VisualPrefabs";

        /// <summary>
        /// The two normal maps the BC5 quality gate rejected, left uncompressed on
        /// purpose.
        /// <para>
        /// Both are flat 512x256 tangent-space maps — every texel effectively
        /// (128, 128, 255) — and block compression of a constant field produced a
        /// measurable error against a perfectly compressible source, which is the
        /// one shape of input where BC5 is worse than no compression at all. They
        /// are pinned here so that a later pass tidying the format column of a
        /// report cannot quietly force them back and call the table cleaner.
        /// </para>
        /// </summary>
        private static readonly string[] DeliberatelyUncompressedNormals =
        {
            "normal_512x256_2888b776cb18",
            "normal_512x256_e6ee84d4ccc6"
        };

        private static string ProjectRoot => Directory.GetParent(Application.dataPath).FullName;

        private static string Abs(string relative) => Path.Combine(ProjectRoot, relative);

        private static string Relative(string absolute) =>
            "Assets" + absolute.Substring(Application.dataPath.Length).Replace('\\', '/');

        private static NebulaJsonValue ManifestDocument =>
            NebulaJsonValue.Parse(File.ReadAllText(Abs(NebulaVisualTextureManifest.ManifestPath)));

        // ---- pixel integrity --------------------------------------------------

        /// <summary>
        /// Every generated texture file is byte-identical to the embedded image it
        /// stands in for.
        /// <para>
        /// This is what makes "black texture 0", "inverted normal 0" and "wrong
        /// colour 0" statements of fact rather than of confidence. The manifest
        /// records the SHA-256 of the source blob for each texture; recomputing it
        /// from the file on disk and getting the same digest means the extraction
        /// copied bytes and nothing between the GLB and the asset touched a pixel.
        /// </para>
        /// <para>
        /// It also catches the quieter failure: an asset regenerated by a later run
        /// with a different encoder would still look right and would still pass
        /// every rendered comparison, while no longer being the thing the manifest
        /// says it is.
        /// </para>
        /// </summary>
        [Test]
        public void EveryGeneratedTextureIsAByteForByteCopyOfTheImageItReplaced()
        {
            NebulaJsonValue textures = ManifestDocument["textures"];
            Assert.IsNotNull(textures, "the manifest has no texture list");
            Assert.Greater(textures.Count, 40, "the manifest texture walk found almost nothing");

            var problems = new List<string>();
            for (int index = 0; index < textures.Count; index++)
            {
                NebulaJsonValue texture = textures[index];
                string path = texture["assetPath"].AsString();
                string recorded = texture["sourceHash"].AsString();

                if (!File.Exists(Abs(path))) { problems.Add(path + ": not on disk"); continue; }

                string actual;
                using (var sha = SHA256.Create())
                using (FileStream stream = File.OpenRead(Abs(path)))
                    actual = string.Concat(sha.ComputeHash(stream).Select(b => b.ToString("x2")));

                if (!string.Equals(actual, recorded, StringComparison.Ordinal))
                    problems.Add($"{path}: {actual} != recorded {recorded}");
            }

            Assert.IsEmpty(problems,
                "these generated textures are no longer verbatim copies of the images they "
                + "replaced, so no pixel-level claim about them holds:\n  "
                + string.Join("\n  ", problems));
        }

        /// <summary>
        /// Import settings on disk say what the manifest says they were asked to
        /// say — colour space above all.
        /// <para>
        /// Colour space is the one import setting that changes what a texture
        /// <i>means</i> rather than how sharp it is. An sRGB flag on a
        /// metallic-roughness or normal map runs a gamma curve over material data,
        /// which reads as a subtly wrong surface instead of an obvious error, and
        /// it is the exact failure the dedup key was designed to prevent. Checking
        /// the importer as well as the key closes the gap between "the pipeline
        /// intended the right thing" and "the asset actually has it".
        /// </para>
        /// <para>
        /// Alpha source is checked alongside it because it is what an alpha fringe
        /// is made of: an alpha channel kept on a texture that no material samples
        /// through a transparent mode leaves a halo wherever the encoder guessed,
        /// and a channel dropped from one that does leaves a hard edge.
        /// </para>
        /// </summary>
        [Test]
        public void EveryGeneratedTextureCarriesTheColourSpaceAndAlphaPolicyItWasGiven()
        {
            NebulaJsonValue textures = ManifestDocument["textures"];
            var problems = new List<string>();
            int checkedTextures = 0;

            for (int index = 0; index < textures.Count; index++)
            {
                NebulaJsonValue texture = textures[index];
                string path = texture["assetPath"].AsString();
                var importer = AssetImporter.GetAtPath(path) as TextureImporter;
                if (importer == null) { problems.Add(path + ": no TextureImporter"); continue; }
                checkedTextures++;

                NebulaJsonValue plan = texture["import"];
                bool wantSrgb = plan["sRGBTexture"].AsBool(true);
                string wantType = plan["textureType"].AsString();
                string wantAlpha = plan["alphaSource"].AsString();

                if (importer.sRGBTexture != wantSrgb)
                    problems.Add($"{path}: sRGB is {importer.sRGBTexture}, the manifest asked for {wantSrgb}");

                bool wantNormal = string.Equals(wantType, "NormalMap", StringComparison.Ordinal);
                bool isNormal = importer.textureType == TextureImporterType.NormalMap;
                if (wantNormal != isNormal)
                    problems.Add($"{path}: textureType is {importer.textureType}, the manifest asked for {wantType}");

                // A normal map is data by definition; sRGB on one is always wrong,
                // whatever the manifest happens to record.
                if (isNormal && importer.sRGBTexture)
                    problems.Add(path + ": a normal map is flagged sRGB");

                string actualAlpha = importer.alphaSource.ToString();
                if (!string.Equals(actualAlpha, wantAlpha, StringComparison.Ordinal))
                    problems.Add($"{path}: alphaSource is {actualAlpha}, the manifest asked for {wantAlpha}");
            }

            Assert.Greater(checkedTextures, 40, "the importer walk found almost nothing");
            Assert.IsEmpty(problems, string.Join("\n  ", problems));
        }

        /// <summary>
        /// The two normal maps the BC5 gate rejected are still uncompressed, and no
        /// other texture quietly joined them.
        /// <para>
        /// Pinned in both directions. Forcing these two back to BC5 for a tidier
        /// format column would reintroduce the error the gate measured; letting a
        /// third texture fall out of compression would cost VRAM that nothing in
        /// the quality report justifies.
        /// </para>
        /// </summary>
        [Test]
        public void TheTwoNormalMapsThatFailedTheBc5GateAreStillUncompressed()
        {
            NebulaJsonValue textures = ManifestDocument["textures"];
            var uncompressed = new List<string>();

            for (int index = 0; index < textures.Count; index++)
            {
                NebulaJsonValue texture = textures[index];
                string format = texture["import"]["format"].AsString();
                if (!string.Equals(format, "BC7", StringComparison.Ordinal)
                    && !string.Equals(format, "BC5", StringComparison.Ordinal))
                    uncompressed.Add(texture["id"].AsString());
            }

            CollectionAssert.AreEquivalent(DeliberatelyUncompressedNormals, uncompressed,
                "the set of uncompressed textures changed; forcing the two flat normal maps back "
                + "to BC5 reintroduces the error the quality gate measured, and any new entry here "
                + "is VRAM nothing has justified");
        }

        /// <summary>
        /// The four star classes stayed out of the dedup set entirely.
        /// <para>
        /// Stars are the one shipping visual family with no GLB behind it:
        /// <c>NebulaProducedVisualCatalog</c> resolves each class to a pair of
        /// authored textures under <c>Resources/VisualTextures/Stars</c>, loaded by
        /// path, and the optimizer only ever reads images embedded in models. That
        /// is why the star row of the visual matrix is photographed through the
        /// celestial body a star sits inside rather than through a star prefab, and
        /// this is the assertion that keeps that explanation true: if a star
        /// texture ever appeared under the generated root, the row would be
        /// measuring the wrong thing and the note on twelve cells would be a lie.
        /// </para>
        /// <para>
        /// Both directions again. The eight star textures must still be where the
        /// resolver looks for them, and none of their pixels may have been pulled
        /// into the shared set.
        /// </para>
        /// </summary>
        [Test]
        public void NoStarTextureWasEverDrawnIntoTheDedupSet()
        {
            string[] stars = Directory.GetFiles(
                Abs("Assets/Resources/VisualTextures/Stars"), "*.png", SearchOption.AllDirectories);
            Assert.AreEqual(8, stars.Length,
                "the star texture set changed; four classes x (surface, corona) is eight files");

            var starHashes = new HashSet<string>(StringComparer.Ordinal);
            foreach (string path in stars)
                using (var sha = SHA256.Create())
                using (FileStream stream = File.OpenRead(path))
                    starHashes.Add(string.Concat(sha.ComputeHash(stream).Select(b => b.ToString("x2"))));

            NebulaJsonValue textures = ManifestDocument["textures"];
            var collisions = new List<string>();
            for (int index = 0; index < textures.Count; index++)
            {
                NebulaJsonValue texture = textures[index];
                if (starHashes.Contains(texture["sourceHash"].AsString()))
                    collisions.Add(texture["assetPath"].AsString());
            }

            Assert.IsEmpty(collisions,
                "a star texture was extracted into the shared set:\n  " + string.Join("\n  ", collisions));
        }

        /// <summary>
        /// The dynamic font atlas carries no baked glyph cache.
        /// <para>
        /// <c>LiberationSans SDF - Fallback.asset</c> bakes any glyph the base font
        /// lacks straight into itself the moment something renders one, so its bytes
        /// change whenever anybody runs the game — three glyphs after one session,
        /// eleven after another, a 262 144-byte atlas page either way. None of it
        /// ships: <c>m_ClearDynamicDataOnBuild: 1</c> means TextMesh Pro empties the
        /// whole cache during every player build, so what a player receives is the
        /// cleared form and nothing else.
        /// </para>
        /// <para>
        /// That is why this gate exists rather than a raw-hash pin alone. The
        /// provenance record carries the cleared hash — the bytes the build actually
        /// consumes — and a working tree carrying a session's cache makes that record
        /// look wrong while nothing is actually wrong. Failing here says exactly what
        /// to do about it: run <c>Nebula/Release/Clear dynamic font atlases</c>, which
        /// reproduces the cleared form byte for byte.
        /// </para>
        /// <para>
        /// Nothing is lost by clearing. A dynamic atlas exists so it can bake a glyph
        /// on demand; the cache is a cache.
        /// </para>
        /// </summary>
        [Test]
        public void TheDynamicFontAtlasCarriesNoBakedGlyphCache()
        {
            const string path = "Assets/TextMesh Pro/Resources/Fonts & Materials/"
                                + "LiberationSans SDF - Fallback.asset";
            Assert.IsTrue(File.Exists(Abs(path)), "the TMP fallback font asset is gone");

            string text = File.ReadAllText(Abs(path));
            Assert.IsTrue(text.Contains("m_ClearDynamicDataOnBuild: 1"),
                "the fallback font no longer clears its dynamic data on build, so the cache it "
                + "accumulates would start shipping — several hundred KB of atlas nobody authored");

            var stale = new List<string>();
            if (!text.Contains("m_GlyphTable: []")) stale.Add("m_GlyphTable");
            if (!text.Contains("m_CharacterTable: []")) stale.Add("m_CharacterTable");
            if (!text.Contains("m_UsedGlyphRects: []")) stale.Add("m_UsedGlyphRects");
            if (!text.Contains("m_CompleteImageSize: 0")) stale.Add("atlas texture");

            Assert.IsEmpty(stale,
                "an editor session baked glyphs into the dynamic font atlas ("
                + string.Join(", ", stale) + " is populated). Nothing is wrong with the font — "
                + "this is a cache, and the build discards it — but the committed bytes and the "
                + "provenance hash now describe a working-tree state rather than what ships. "
                + "Run Nebula/Release/Clear dynamic font atlases.");
        }

        /// <summary>
        /// Exactly one place in the project may rewrite a dynamic font atlas, and it
        /// is an editor tool.
        /// <para>
        /// This is the companion to the gate above, and it exists because that gate
        /// answers "is the cache populated?" without answering "who populated it?".
        /// The answer turns out to be nothing anyone would call a culprit: the
        /// interface is Turkish, and the base <c>LiberationSans SDF</c> atlas is a
        /// static 250-glyph ASCII/Latin-1 set that does not contain
        /// <c>İ Ş Ğ ı ş ğ</c> (Latin Extended-A), the four arrows in
        /// <c>NebulaParentMenuScreen</c>'s key-prompt strip, or the U+2212 minus on
        /// the planet-context and settings steppers. Those eleven characters are
        /// exactly the eleven the fallback keeps baking. Every one of them arrives
        /// through ordinary composition — <c>PresentationInstaller</c> builds the
        /// parent menu and the planet-context HUD on every session — so any editor
        /// session that renders the game repopulates the cache, and no fixture is
        /// doing anything unusual. There is no test-side clone to reach for either:
        /// TMP resolves the fallback through the shared font asset that production
        /// itself loads, and giving tests a different one would mean a test-only
        /// branch in production code.
        /// </para>
        /// <para>
        /// What can be pinned is the blast radius, which is what this does. The one
        /// API that empties a baked cache must appear once, in a file under an
        /// <c>Editor/</c> folder — Unity excludes those from every player build, so
        /// the cleanup can never run in a player's hands, where clearing a live
        /// atlas would blank the interface until TMP rebuilt it. And no test may
        /// call it at all: a fixture that clears or rewrites the tracked asset would
        /// make the gate above pass or fail according to test order, which is
        /// strictly worse than a cache that at least drifts honestly.
        /// </para>
        /// </summary>
        [Test]
        public void OnlyTheEditorOnlyHygieneToolMayRewriteADynamicFontAtlas()
        {
            // The needle is the INVOCATION, assembled rather than written out, and both
            // halves of that are deliberate. Matching "name(" instead of the bare name
            // means a file that merely discusses the API is not a caller; assembling it
            // from two pieces means this fixture's own source does not contain the
            // needle, so the scanner is not blinded to itself the way a "skip my own
            // file" exclusion would blind it — a test that genuinely called this would
            // still be caught here.
            const string mutatingApi = "ClearFontAssetData";
            string invocation = mutatingApi + "(";

            var callers = new List<string>();
            foreach (string absolute in Directory.EnumerateFiles(Abs("Assets"), "*.cs", SearchOption.AllDirectories))
            {
                if (!File.ReadAllText(absolute).Contains(invocation)) continue;
                callers.Add(absolute.Substring(ProjectRoot.Length + 1).Replace('\\', '/'));
            }

            // Ordered so each assertion can actually fire. The test-caller check goes
            // first because it is true of a single caller or of five; put behind the
            // count check it would only ever be reachable in the one arrangement the
            // count check already rejects, which is a dead assertion wearing a belt.
            var offendingTests = callers.Where(c => c.StartsWith("Assets/Tests/")).ToList();
            Assert.IsEmpty(offendingTests,
                "a test mutates the tracked font atlas: " + string.Join(", ", offendingTests)
                + ". TheDynamicFontAtlasCarriesNoBakedGlyphCache would then pass or fail on test order "
                + "rather than on the committed bytes.");

            Assert.AreEqual(1, callers.Count,
                $"{mutatingApi} is the one call that empties a baked font atlas, and it must stay in a "
                + "single editor tool. Found: " + string.Join(", ", callers));

            string owner = callers[0];
            Assert.IsTrue(owner.Split('/').Contains("Editor"),
                $"{owner} calls {mutatingApi} from outside an Editor/ folder, so it compiles into the "
                + "player. Clearing a dynamic atlas at runtime blanks every glyph the base font lacks "
                + "until TMP rebuilds it — the whole Turkish interface, mid-session.");
        }

        // ---- font glyph coverage ----------------------------------------------

        private const string PrimaryFontPath =
            "Assets/TextMesh Pro/Resources/Fonts & Materials/LiberationSans SDF.asset";

        private const string CharacterInventoryPath =
            "Tools/Fonts/player-character-inventory.txt";

        /// <summary>
        /// Every codepoint the primary atlas's character table carries.
        /// <para>
        /// Read out of the YAML rather than through <c>TMP_FontAsset</c>, so the
        /// gate describes the committed bytes. Loading the asset would answer for
        /// whatever the editor currently holds in memory, which on a machine that
        /// has just rendered the game is not the same thing.
        /// </para>
        /// <para>
        /// <c>m_Unicode</c> is unique to <c>TMP_Character</c>: the glyph table
        /// keys on <c>m_Index</c>, so there is nothing else in the file for this
        /// to accidentally match.
        /// </para>
        /// </summary>
        private static HashSet<uint> StaticAtlasCharacters()
        {
            const string key = "m_Unicode: ";
            var codes = new HashSet<uint>();

            foreach (string line in File.ReadAllLines(Abs(PrimaryFontPath)))
            {
                string trimmed = line.Trim();
                if (!trimmed.StartsWith(key, StringComparison.Ordinal)) continue;
                if (uint.TryParse(trimmed.Substring(key.Length), NumberStyles.Integer,
                        CultureInfo.InvariantCulture, out uint unicode))
                    codes.Add(unicode);
            }

            return codes;
        }

        /// <summary>Codepoints listed in the generated inventory, in file order.</summary>
        private static List<uint> InventoryCharacters()
        {
            var codes = new List<uint>();

            foreach (string line in File.ReadAllLines(Abs(CharacterInventoryPath)))
            {
                string trimmed = line.Trim();
                if (trimmed.Length == 0 || trimmed.StartsWith("#", StringComparison.Ordinal)) continue;

                string field = trimmed.Split('\t')[0];
                Assert.IsTrue(field.StartsWith("U+", StringComparison.Ordinal),
                    $"{CharacterInventoryPath}: unparsable row '{line}'");
                codes.Add(uint.Parse(field.Substring(2), NumberStyles.HexNumber,
                    CultureInfo.InvariantCulture));
            }

            return codes;
        }

        /// <summary>
        /// The atlas that ships contains every character the game can draw.
        /// <para>
        /// The stock TextMesh Pro atlas covered <c>32 - 126, 160 - 255,
        /// 8192 - 8303</c> — ASCII and Latin-1 — and this interface is Turkish.
        /// <c>Ğ ğ İ ı Ş ş</c> are Latin Extended-A and were outside it, as were
        /// the arrows on the parent menu's key strip and the U+2212 minus on the
        /// steppers. Every one of them missed the primary atlas and resolved
        /// through the DYNAMIC fallback, and that single gap produced two
        /// failures that looked unrelated: a <c>TMP_SubMeshUI</c> child object per
        /// affected label — <c>TMPro_UGUI_Private.cs:1403</c> spawns one per
        /// material reference, and a fallback font is a second material — which a
        /// 1000-cycle soak saw as climbing <c>sessionui</c> counts, and a fallback
        /// asset whose bytes changed whenever anybody ran the game.
        /// </para>
        /// <para>
        /// The comparison is inventory against atlas and nothing else. A list of
        /// characters written out here would be this test carrying its own copy of
        /// the answer, and a copy of the answer agrees with a narrowed atlas as
        /// happily as with a correct one. What the inventory must itself contain
        /// is asserted one test down, where narrowing would actually begin.
        /// </para>
        /// </summary>
        [Test]
        public void TheStaticAtlasCoversEveryPlayerFacingCharacter()
        {
            HashSet<uint> atlas = StaticAtlasCharacters();
            Assert.Greater(atlas.Count, 0, $"{PrimaryFontPath} has no character table at all");

            var missing = InventoryCharacters().Where(c => !atlas.Contains(c))
                .Select(c => $"U+{c:X4}").ToList();

            Assert.IsEmpty(missing,
                $"{missing.Count} character(s) in {CharacterInventoryPath} are not in the shipped "
                + "atlas: " + string.Join(" ", missing.Take(24))
                + (missing.Count > 24 ? " ..." : string.Empty)
                + ". Every one of them will resolve through LiberationSans SDF - Fallback.asset "
                + "instead, which grows a HideFlags.DontSave sub-object per label and rewrites its "
                + "own .asset file on disk. Run Nebula/Release/Rebuild player font atlas.");
        }

        /// <summary>
        /// The inventory the atlas is built from is intact, and still asks for the
        /// characters this whole arrangement exists for.
        /// <para>
        /// This is upstream of the coverage gate and exists because that gate
        /// trusts this file. A truncated or hand-edited inventory asks for fewer
        /// characters, the next rebuild bakes fewer, and the two files then agree
        /// with each other perfectly while the game renders boxes. That is why the
        /// named set lives here rather than next to the atlas comparison: this is
        /// the point where narrowing starts, so this is the point worth pinning.
        /// </para>
        /// <para>
        /// Twelve characters, in two groups, each with a specific history. The six
        /// Turkish letters are the original defect. The six symbols replaced
        /// <c>◆ ◇ △ ⟡ ┄</c> and a checkmark on the strategic map legend, the layer
        /// toggles and the two severity ramps — LiberationSans.ttf has no glyph
        /// for any of those, so they had been drawing as identical empty boxes,
        /// and a legend whose entire job is telling six things apart was showing
        /// one shape and five boxes.
        /// </para>
        /// <para>
        /// Sortedness and distinctness are not tidiness. The rebuild feeds this
        /// list to the glyph packer in order, so a reordered file produces a
        /// different atlas layout from identical inputs and a clean checkout stops
        /// reproducing the committed asset.
        /// </para>
        /// </summary>
        [Test]
        public void ThePlayerCharacterInventoryIsIntact()
        {
            string path = Abs(CharacterInventoryPath);
            Assert.IsTrue(File.Exists(path),
                $"{CharacterInventoryPath} is gone. It is the only record of which characters the "
                + "shipped atlas is supposed to contain. Regenerate it with "
                + "`python3 Tools/Fonts/nebula-font-inventory.py`.");

            List<uint> codes = InventoryCharacters();

            string countLine = File.ReadAllLines(path)
                .FirstOrDefault(l => l.StartsWith("# COUNT ", StringComparison.Ordinal));
            Assert.IsNotNull(countLine, $"{CharacterInventoryPath} has no '# COUNT n' header");

            int declared = int.Parse(countLine.Substring("# COUNT ".Length).Trim(),
                CultureInfo.InvariantCulture);
            Assert.AreEqual(declared, codes.Count,
                $"{CharacterInventoryPath} declares {declared} characters and lists {codes.Count}. "
                + "It has been truncated or hand-edited; regenerate it.");

            CollectionAssert.AreEqual(codes.Distinct().OrderBy(c => c).ToList(), codes,
                $"{CharacterInventoryPath} is not sorted-and-distinct, so the packer would consume "
                + "it in a different order and the rebuild would stop being reproducible.");

            var required = new (uint Code, string Why)[]
            {
                (0x011E, "Ğ"), (0x011F, "ğ"), (0x0130, "İ"), (0x0131, "ı"),
                (0x015E, "Ş"), (0x015F, "ş"),
                (0x2666, "♦ system / layer on / severity high"),
                (0x25CA, "◊ signal / layer off / severity low"),
                (0x2206, "∆ threat"),
                (0x25CB, "○ discovery"),
                (0x2500, "─ route"),
                (0x25B2, "▲ ship / severity critical"),
            };

            var absent = required.Where(r => !codes.Contains(r.Code))
                .Select(r => $"U+{r.Code:X4} {r.Why}").ToList();

            Assert.IsEmpty(absent,
                "the inventory no longer asks for " + string.Join(", ", absent)
                + ", so the next rebuild would drop them out of the shipped atlas and they would "
                + "go back to resolving through the dynamic fallback — or, for the symbols, back "
                + "to drawing as empty boxes.");
        }

        /// <summary>
        /// The primary atlas ships static, single-page and non-readable.
        /// <para>
        /// Three properties, one purpose: that the font a player receives cannot
        /// change at runtime and costs what it says it costs.
        /// </para>
        /// <para>
        /// <c>m_AtlasPopulationMode: 0</c> is the whole architecture — a dynamic
        /// primary would bake glyphs into itself in a player's hands.
        /// <c>m_IsReadable: 0</c> is two megabytes: baking forces the atlas
        /// texture readable and does not put it back, so an unrestored rebuild
        /// ships a permanent CPU-side copy of a page only the shader reads. And a
        /// single entry under <c>m_AtlasTextures</c> matters because a second
        /// atlas page arrives with a second material that no prefab in the project
        /// is bound to; the answer to an atlas that has run out of room is a
        /// bigger page, not another one.
        /// </para>
        /// </summary>
        [Test]
        public void ThePrimaryFontAtlasShipsStaticAndNonReadable()
        {
            string text = File.ReadAllText(Abs(PrimaryFontPath));

            Assert.IsTrue(text.Contains("m_AtlasPopulationMode: 0"),
                "the primary font atlas is no longer static, so a player build would bake glyphs "
                + "into it at runtime — the drift this whole arrangement exists to remove, moved "
                + "from the fallback to the asset every label uses.");

            Assert.IsTrue(text.Contains("m_IsReadable: 0"),
                "the primary atlas texture ships readable. Baking forces that flag true and never "
                + "restores it; left alone it costs a CPU-side copy of the whole page for a "
                + "texture only the shader samples. Rerun Nebula/Release/Rebuild player font atlas.");

            int pages = text.Split(new[] { "m_AtlasTextures:" }, StringSplitOptions.None).Length - 1;
            Assert.AreEqual(1, pages, "expected exactly one m_AtlasTextures block");
        }

        /// <summary>
        /// The shared material describes the atlas page that actually exists.
        /// <para>
        /// TextMesh Pro writes <c>_TextureWidth</c> and <c>_TextureHeight</c> once,
        /// when a font asset is first created (<c>TMP_FontAsset.cs:507</c>), and
        /// nothing recomputes them from the font asset afterwards — not on load,
        /// not at runtime. So resizing the atlas without updating them leaves the
        /// SDF shader reading the dimensions of a page that is no longer there for
        /// its screen-space derivatives.
        /// </para>
        /// <para>
        /// Pinned rather than trusted because of how the defect presents: text
        /// that is subtly soft or over-sharp at some point sizes and correct at
        /// others. Nothing is missing, nothing throws, and a screenshot diff at
        /// one size can easily agree with itself. The page went from 1024x1024 to
        /// 1024x2048 to fit the Turkish glyphs — the stock atlas was already 96%
        /// full — so this pairing has been broken once already.
        /// </para>
        /// </summary>
        [Test]
        public void TheFontMaterialAgreesWithTheAtlasItSamples()
        {
            string text = File.ReadAllText(Abs(PrimaryFontPath));

            int Field(string pattern, string what)
            {
                Match match = Regex.Match(text, pattern);
                Assert.IsTrue(match.Success, $"{PrimaryFontPath} has no {what}");
                return (int)float.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture);
            }

            int atlasWidth = Field(@"\n  m_AtlasWidth: (\d+)", "m_AtlasWidth");
            int atlasHeight = Field(@"\n  m_AtlasHeight: (\d+)", "m_AtlasHeight");
            int shaderWidth = Field(@"_TextureWidth: ([\d.]+)", "_TextureWidth");
            int shaderHeight = Field(@"_TextureHeight: ([\d.]+)", "_TextureHeight");

            Assert.AreEqual(atlasWidth, shaderWidth,
                $"the font material says the atlas is {shaderWidth} wide and the font asset says "
                + $"{atlasWidth}. The SDF shader reads the material's value, so text will render "
                + "subtly soft or over-sharp — at some sizes and not others, which is why this is "
                + "a gate and not something a screenshot would settle. Rerun "
                + "Nebula/Release/Rebuild player font atlas, which sets both.");

            Assert.AreEqual(atlasHeight, shaderHeight,
                $"the font material says the atlas is {shaderHeight} tall and the font asset says "
                + $"{atlasHeight}. Same defect as the width, same fix.");
        }

        // ---- material binding across LOD levels -------------------------------

        /// <summary>
        /// Every bound material is the manifest's own replacement for the authored
        /// material in that exact slot — at every LOD level.
        /// <para>
        /// This is the "wrong material during LOD pop" gate. LOD1 and LOD2
        /// renderers come from separate GLBs under <c>Derived/LOD</c>, so their
        /// materials were deduplicated independently of LOD0's; a rebind that
        /// matched by index or by name rather than by authored identity would put
        /// LOD1's surface on LOD0's mesh, and the symptom is a model that changes
        /// appearance as the camera pulls back — the one artefact a static
        /// screenshot at a single distance cannot show.
        /// </para>
        /// <para>
        /// The comparison is by authored material name against the manifest's
        /// <c>replaces</c> list, which is the record of what each generated
        /// material stands for. Matching on the bound material's own name would be
        /// circular.
        /// </para>
        /// </summary>
        [Test]
        public void EveryLodLevelBindsTheReplacementForItsOwnAuthoredMaterial()
        {
            NebulaJsonValue materials = ManifestDocument["materials"];
            var replacementsFor = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);

            for (int index = 0; index < materials.Count; index++)
            {
                NebulaJsonValue material = materials[index];
                string id = material["id"].AsString();
                NebulaJsonValue replaces = material["replaces"];
                for (int slot = 0; slot < replaces.Count; slot++)
                {
                    string authored = replaces[slot]["materialName"].AsString() ?? string.Empty;
                    if (!replacementsFor.TryGetValue(authored, out HashSet<string> ids))
                        replacementsFor[authored] = ids = new HashSet<string>(StringComparer.Ordinal);
                    ids.Add(id);
                }
            }

            Assert.Greater(replacementsFor.Count, 20, "the manifest replacement map is empty");

            var problems = new List<string>();
            int compared = 0;

            foreach (string prefabPath in WrapperPrefabs())
            {
                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
                if (prefab == null) continue;

                foreach (Renderer renderer in prefab.GetComponentsInChildren<Renderer>(true))
                {
                    var source = PrefabUtility.GetCorrespondingObjectFromSource(renderer) as Renderer;
                    if (source == null) continue;

                    Material[] bound = renderer.sharedMaterials;
                    Material[] authored = source.sharedMaterials;
                    if (bound.Length != authored.Length) continue;

                    for (int slot = 0; slot < bound.Length; slot++)
                    {
                        if (bound[slot] == null || authored[slot] == null) continue;
                        compared++;

                        if (!replacementsFor.TryGetValue(authored[slot].name, out HashSet<string> ids))
                        {
                            problems.Add($"{Path.GetFileName(prefabPath)} / {renderer.name}[{slot}]: "
                                         + $"the manifest records no replacement for \"{authored[slot].name}\"");
                            continue;
                        }

                        if (!ids.Contains(bound[slot].name))
                            problems.Add($"{Path.GetFileName(prefabPath)} / {renderer.name}[{slot}]: "
                                         + $"bound to \"{bound[slot].name}\" but \"{authored[slot].name}\" "
                                         + "is replaced by " + string.Join("/", ids));
                    }
                }
            }

            Assert.Greater(compared, 9000, "the material binding walk found almost nothing");
            Assert.IsEmpty(problems, string.Join("\n  ", problems.Distinct().Take(25)));
        }

        /// <summary>
        /// Every rendering node in every wrapper is still an instance of a node in
        /// its authored model.
        /// <para>
        /// The "authored node / part / collider difference: 0" gate, asserted as a
        /// property of the graph rather than as a count. A rebind that replaced a
        /// nested prefab instance with a hand-built copy of the same mesh would keep
        /// the node count identical, keep the anchor census identical, render
        /// identically at every LOD — and would have silently severed the link to
        /// the source model, so the next model update would reach nothing.
        /// <see cref="PrefabUtility.GetCorrespondingObjectFromSource"/> returning
        /// non-null is the only thing that distinguishes the two.
        /// </para>
        /// </summary>
        [Test]
        public void EveryRenderingNodeIsStillAnInstanceOfItsAuthoredModel()
        {
            var problems = new List<string>();
            int total = 0, linked = 0, colliders = 0, lodGroups = 0;

            foreach (string prefabPath in WrapperPrefabs())
            {
                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
                if (prefab == null) continue;

                colliders += prefab.GetComponentsInChildren<Collider>(true).Length;
                lodGroups += prefab.GetComponentsInChildren<LODGroup>(true).Length;

                foreach (Renderer renderer in prefab.GetComponentsInChildren<Renderer>(true))
                {
                    total++;
                    if (PrefabUtility.GetCorrespondingObjectFromSource(renderer) != null) linked++;
                    else problems.Add($"{Path.GetFileName(prefabPath)} / {renderer.name}: "
                                      + "no longer resolves to a node in an authored model");
                }
            }

            Assert.Greater(total, 1000, "the wrapper renderer walk found almost nothing");
            Assert.IsEmpty(problems, string.Join("\n  ", problems.Take(25)));
            Assert.AreEqual(total, linked);
            Assert.Greater(lodGroups, 0, "the wrappers lost every LOD group");
            Assert.GreaterOrEqual(colliders, 0);
        }

        private static IEnumerable<string> WrapperPrefabs() =>
            Directory.GetFiles(Abs(PrefabRoot), "*.prefab", SearchOption.AllDirectories)
                .Select(Relative)
                .OrderBy(path => path, StringComparer.Ordinal);
    }
